#!/usr/bin/env bash
# lessons-index.sh — generate INDEX.md from lesson frontmatter (#41).
#
# The index is the catalog the session judges relevance against (see the
# session-judged loader, #42). It is GENERATED, never hand-edited, so it can
# never silently miss a lesson. Each lesson carries YAML frontmatter:
#
#   ---
#   date: 2026-06-28          # ISO; drives recency + sort (replaces the old number)
#   tier: lesson              # rules | lesson | incident
#   summary: <one line>       # what the session judges relevance from
#   tags: [a, b]              # optional
#   legacy_id: "086"          # optional; preserves old #086/L086 cross-refs
#   ---
#
# Output: $LESSONS_DIR/INDEX.md, grouped by tier (rules, lessons, incidents),
# each sorted newest-first by date, one line per lesson.
#
#   lessons-index.sh            # (re)write INDEX.md
#   lessons-index.sh --check    # exit non-zero if INDEX.md is stale (CI drift gate)
#   lessons-index.sh --stdout   # print the index instead of writing
#
#   Env: LESSONS_DIR (default: tasks/lessons)
set -euo pipefail

LESSONS_DIR="${LESSONS_DIR:-tasks/lessons}"
MODE=write
case "${1:-}" in
  --check)  MODE=check ;;
  --stdout) MODE=stdout ;;
  "")       ;;
  *) echo "lessons-index: unknown arg: $1" >&2; exit 2 ;;
esac

[[ -d "$LESSONS_DIR" ]] || { echo "lessons-index: no such dir: $LESSONS_DIR" >&2; exit 2; }

# Collect rows as "tier\tdate\tfilename\tsummary" in ONE awk pass over every
# lesson (#1748). This used to call a per-file `fm` awk three times plus
# `basename` (~5 forks per lesson, ~1,200 per run): ~3s on an idle Mac and past
# the vitest timeout under parallel load, growing with every lesson added. The
# process count is now constant in the corpus size (pinned by
# scripts/lib/__tests__/lessonsIndexSpawns.test.ts).
#
# Frontmatter is the YAML block between a first-line `---` and the next `---`;
# a scalar is the first `key:` line in it, whitespace after the colon stripped.
# A lesson with no `tier` falls back to its directory name; unknown tiers land
# in `lessons`. The first lesson (in path order) missing `date` or `summary`
# aborts with exit 3; awk drains its input after an error so the upstream
# `sort` never SIGPIPEs under `pipefail`.
#
# `LC_ALL=C` on every sort (#1370): collation is locale-dependent, so the same
# corpus generated a DIFFERENT index on macOS than on the ubuntu CI runner —
# `en_CA.UTF-8` folds case (`IA-tab-strip…` lands among the `i`s) while CI's C
# locale orders by byte (`I` < `a`, so it leads). The drift gate then failed for
# whoever regenerated on the other platform, blaming a file they never touched.
# Scoped to `sort` rather than exported, so awk still reads the UTF-8 summaries
# (em-dashes, curly quotes) as characters.
rows="$(find "$LESSONS_DIR" -name '*.md' | LC_ALL=C sort | awk '
  function canon(t) {
    if (t == "rule" || t == "rules") return "rules"
    if (t == "incident" || t == "incidents") return "incidents"
    return "lessons"   # lesson|lessons and the default bucket
  }
  function scalar(line, k,   v) { v = line; sub("^" k ":[[:space:]]*", "", v); return v }
  err { next }
  {
    f = $0
    base = f; sub(/.*\//, "", base)
    if (base == "INDEX.md" || base == "README.md") next
    date = ""; summary = ""; tier = ""; hasd = 0; hass = 0; hast = 0; n = 0
    while ((getline line < f) > 0) {
      if (++n == 1) { if (line == "---") continue; else break }
      if (line == "---") break
      if (!hasd && index(line, "date:") == 1)    { date = scalar(line, "date"); hasd = 1 }
      if (!hass && index(line, "summary:") == 1) { summary = scalar(line, "summary"); hass = 1 }
      if (!hast && index(line, "tier:") == 1)    { tier = scalar(line, "tier"); hast = 1 }
    }
    close(f)
    if (tier == "") { dir = f; sub(/\/[^\/]*$/, "", dir); sub(/.*\//, "", dir); tier = dir }
    tier = canon(tier)
    if (date == "")    { print "lessons-index: " f " missing '\''date'\'' frontmatter" > "/dev/stderr"; err = 3; next }
    if (summary == "") { print "lessons-index: " f " missing '\''summary'\'' frontmatter" > "/dev/stderr"; err = 3; next }
    printf "%s\t%s\t%s\t%s\n", tier, date, base, summary
  }
  END { exit err }
')"

render() {
  printf '<!-- Generated by scripts/lessons-index.sh — do not edit by hand. -->\n'
  printf '# Lessons index\n'
  local tier label
  for tier in rules lessons incidents; do
    case "$tier" in
      rules)     label="rules (always loaded)" ;;
      lessons)   label="lessons (manifest-pinned + session-judged)" ;;
      incidents) label="incidents (ref-only — pull when relevant)" ;;
    esac
    # Tier rows, date desc (newest first), ties broken on filename (field 3).
    # `-k3,3` states the tie-break instead of leaning on sort's last-resort
    # WHOLE-LINE comparison, which reaches the filename only because of the
    # current field order and would silently switch to the summary if the row
    # layout ever changed (and vanishes entirely if anyone adds `-s`).
    local body
    body="$(printf '%s' "$rows" | awk -F'\t' -v t="$tier" '$1==t' | LC_ALL=C sort -t$'\t' -k2,2r -k3,3)"
    [[ -z "$body" ]] && continue
    printf '\n## %s\n' "$label"
    printf '%s\n' "$body" | while IFS=$'\t' read -r _ d file summ; do
      [[ -n "$file" ]] && printf -- '- `%s` — %s  (%s)\n' "$file" "$summ" "$d"
    done
  done
}

out="$(render)"

case "$MODE" in
  stdout) printf '%s\n' "$out" ;;
  write)  printf '%s\n' "$out" > "$LESSONS_DIR/INDEX.md"
          echo "lessons-index: wrote $LESSONS_DIR/INDEX.md" >&2 ;;
  check)  if [[ "$(cat "$LESSONS_DIR/INDEX.md" 2>/dev/null)" == "$out" ]]; then
            exit 0
          else
            echo "lessons-index: $LESSONS_DIR/INDEX.md is stale — run scripts/lessons-index.sh" >&2
            exit 1
          fi ;;
esac
