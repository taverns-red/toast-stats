const normalise = (name: string): string =>
  name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]/g, '')

const BY_KEY = new Map(
  Object.entries(ISO_BY_NAME).map(([name, id]) => [normalise(name), id])
)

/** The ISO 3166-1 numeric code for a published country name, or null. */
export function isoIdForCountry(name: string): string | null {
  const key = normalise(name)
  return key ? (BY_KEY.get(key) ?? null) : null
}
